#!/usr/bin/env python3
"""
PolicyStack Documentation Generator

Generates stack/<element>/README.md from Chart.yaml, values.yaml and converters/. The comment lines
directly above a key under config: (and above config: itself) are its description; a blank line
ends the block. Policies and templates are discovered from converters/<policy>/<template>.yaml and
merged with values, and naming, defaults and state follow policy-library 4.0's templates.

Usage:
    python doc-generator.py [--stack-dir stack] [--element <name>]
    python doc-generator.py --check  # exit 1 when a README is stale
"""

import argparse
import re
from pathlib import Path

import yaml

HEADER = "<!-- Generated by tools/doc-generator.py from values.yaml. Do not edit. -->"
MAX_INLINE = 60
STABILITY = "policystk.io/stability"


def camel(name):
    first, *rest = name.split("-")
    return first + "".join(p.capitalize() for p in rest)


def comments(text):
    """Map each mapping key's path to the comment block directly above it, at the key's indent."""
    lines = text.split("\n")
    found = {}

    def above(mark):
        if lines[mark.line][: mark.column].strip() not in ("", "-"):
            return ""  # not the first key on its line, e.g. inside a flow mapping
        block, line, indent = (
            [],
            mark.line,
            lines[mark.line][: mark.column].replace("-", " "),
        )
        while line > 0 and lines[line - 1].startswith(indent + "#"):
            line -= 1
            block.insert(0, lines[line].strip().lstrip("#").strip())
        return " ".join(b for b in block if b)

    def walk(node, path):
        if isinstance(node, yaml.MappingNode):
            for key, value in node.value:
                p = path + (key.value,)
                if text := above(key.start_mark):
                    found[p] = text
                walk(value, p)

    walk(yaml.compose(text, Loader=yaml.SafeLoader), ())
    return found


def cell(text):
    """Escape for a table cell or paragraph: GitHub drops <word> as HTML outside code spans.
    <br> is the generator's own line break."""
    parts = re.split(r"(`[^`]*`)", " ".join(str(text).split()))
    return "".join(
        p if p.startswith("`") else re.sub(r"<(?!br>)", "&lt;", p) for p in parts
    ).replace("|", r"\|")


def table(headers, rows):
    """Markdown table, dropping columns that are empty in every row."""
    keep = [i for i in range(len(headers)) if any(r[i] for r in rows)]
    out = ["| " + " | ".join(headers[i] for i in keep) + " |", "|" + "---|" * len(keep)]
    out += ["| " + " | ".join(cell(r[i]) for i in keep) + " |" for r in rows]
    return out


def flow(value):
    return (
        yaml.safe_dump(
            value, default_flow_style=True, sort_keys=False, width=float("inf")
        )
        .removesuffix("\n...\n")
        .strip()
    )


def scalar(value):
    return not isinstance(value, (dict, list))


class Element:
    def __init__(self, path, chart, values, notes):
        self.path, self.chart, self.notes = path, chart, notes
        self.name = chart.get("name", path.name)
        self.key = camel(self.name)
        self.c = values.get("stack", {}).get(self.key) or {}
        if "configPolicies" in self.c or any(
            isinstance(self.c.get(k), list) for k in ("policies", "operatorPolicies")
        ):
            raise TypeError(
                f"{path}/values.yaml: policies and operatorPolicies must be maps and "
                "configPolicies is gone (policy-library 4.0); run tools/migrate-4.0.py"
            )
        self.stability = (chart.get("annotations") or {}).get(STABILITY)
        if self.stability not in (None, "stable", "preview"):
            raise ValueError(
                f"{path}/Chart.yaml: {STABILITY} is {self.stability!r}; "
                "use stable or preview, or leave it out"
            )
        self.default = self.c.get("default") or {}
        ops = self.c.get("operatorPolicies") or {}
        self.ops = {k: e for k, e in sorted(ops.items()) if isinstance(e, dict)}
        # policy-library.model: converters/<policy>/<template>.yaml, _ names are partials.
        found = {}
        for f in sorted(path.glob("converters/*/*.yaml")):
            p, t = f.parent.name, f.stem
            if not (p.startswith("_") or t.startswith("_")):
                found.setdefault(p, {})[t] = [f"{p}/{t}"]
        declared = self.c.get("policies") or {}
        names = set(found) | set(declared) | ({"install"} if self.ops else set())
        # [(policy, values, [(kind, name, entry, files)])] in policy-library render order.
        self.policies = []
        for p in sorted(names):
            pv = declared.get(p) or {}
            tdecl = pv.get("templates") or {}
            tnames = sorted(set(found.get(p, {})) | set(tdecl))
            if not tnames and not (p == "install" and self.ops):
                raise ValueError(f"{path}/values.yaml: policies.{p} has no templates")
            order = pv.get("orderManifests") or []
            if missing := [t for t in order if t not in tnames]:
                raise ValueError(
                    f"{path}/values.yaml: policies.{p}.orderManifests names {missing}, "
                    "which are not templates of the policy"
                )
            items = []
            for t in order + [t for t in tnames if t not in order]:
                tv = tdecl.get(t) or {}
                files = tv.get("file") or found.get(p, {}).get(t)
                if not files:
                    raise ValueError(
                        f"{path}/values.yaml: policies.{p}.templates.{t} has no file"
                    )
                items.append(
                    ("template", t, tv, [files] if isinstance(files, str) else files)
                )
            if p == "install":
                items += [("operator", k, e, []) for k, e in self.ops.items()]
            self.policies.append((p, pv, items))

    def note(self, *path):
        return self.notes.get(("stack", self.key) + path, "")

    @staticmethod
    def own(entry):
        """policy-library.enabled: on unless enabled: false."""
        return (entry or {}).get("enabled") is not False

    def on(self, pv, items):
        """A Policy renders only when it and at least one of its templates are on."""
        return self.own(pv) and any(self.own(e) for _, _, e, _ in items)

    def resolve(self, dep, owner, kind):
        """Dependency target name, as policy-library.dependencyList resolves it."""
        name = dep["name"]
        if dep.get("raw"):
            pass
        elif dep.get("kind", kind) == "Policy":
            suffix = dep.get("release") or f"{dep.get('element', self.name)}-<cluster>"
            name = f"{name}-{suffix}"
        else:
            name = f"{dep.get('policyRef', owner)}-{name}"
        state = dep.get("compliance", "Compliant")
        return f"`{name}`" + ("" if state == "Compliant" else f" ({state})")

    def waits(self, e, policy):
        wait = e.get("waitForOperator") or []
        wait = [wait] if isinstance(wait, str) else wait
        deps = [f"`install-{o}-status`" for o in wait]
        deps += [
            self.resolve(d, policy, "ConfigurationPolicy")
            for d in e.get("extraDependencies") or []
        ]
        # waitForOperator implies ignorePending.
        pending = e.get("ignorePending")
        if deps and (bool(wait) if pending is None else pending):
            deps.append("compliant while pending")
        return "<br>".join(deps)

    def action(self, kind, e, pv):
        if kind == "template" and e.get("remediationAction") == "InformOnly":
            return "inform (always)"
        return (
            pv.get("remediationAction")
            or self.default.get("remediationAction")
            or "inform"
        )

    def severity(self, e, pv):
        return (
            e.get("severity")
            or pv.get("severity")
            or self.default.get("severity")
            or "low"
        )

    def renders(self, kind, name, e, files):
        def ct(value):
            return "" if (value or "musthave") == "musthave" else f" ({value})"

        if kind == "operator":
            return f"[operator](#operators) `{e.get('subscription', {}).get('name', name)}`{ct(e.get('complianceType'))}"
        out = []
        for f in files:
            text = self.converter(f)
            if re.search(r"^-(?!--)", text, re.MULTILINE):
                # A raw object list sets complianceType on each object; the entry's is ignored.
                found = re.findall(r'complianceType:\s*["\']?(\w+)', text)
                kinds = ", ".join(dict.fromkeys(c for c in found if c != "musthave"))
            else:
                kinds = e.get("complianceType")
            out.append(f"[{f.split('/')[-1]}](converters/{f}.yaml){ct(kinds)}")
        return "<br>".join(out)

    def converter(self, name):
        path = self.path / "converters" / f"{name}.yaml"
        return path.read_text() if path.exists() else ""

    def optional_section(self):
        rows = []
        for p, pv, items in self.policies:
            if not self.own(pv):
                rows.append(
                    (
                        f"Policy [`{p}`](#policy-{p})",
                        pv.get("description") or self.note("policies", p),
                        f"`policies.{p}.enabled: true`",
                    )
                )
            for kind, n, e, _ in items:
                if self.own(e):
                    continue
                key = (
                    ("operatorPolicies", n)
                    if kind == "operator"
                    else ("policies", p, "templates", n)
                )
                needs = "" if self.own(pv) else f" (needs Policy `{p}`)"
                rows.append(
                    (
                        f"{kind} `{p}-{n}`{needs}",
                        e.get("description") or self.note(*key),
                        f"`{'.'.join(key)}.enabled: true`",
                    )
                )
        if not rows:
            return []
        return [
            "## Optional pieces",
            "",
            "Shipped with `enabled: false`. Turn one on in a values layer.",
            "",
            *table(["Entry", "Description", "Turn on with"], rows),
            "",
        ]

    def settings_section(self, config):
        rows, details = [], []

        def walk(node, path):
            for k, v in node.items():
                p, key = path + (k,), ".".join(path + (k,))
                if (
                    isinstance(v, dict)
                    and v
                    and (
                        all(map(scalar, v.values()))
                        or any(self.note("config", *p, ck) for ck in v)
                    )
                ):
                    rows.append((f"`{key}`", self.note("config", *p), ""))
                    walk(v, p)
                elif (not scalar(v) and len(flow(v)) > MAX_INLINE) or (
                    isinstance(v, str) and "\n" in v
                ):
                    rows.append(
                        (
                            f"`{key}`",
                            self.note("config", *p),
                            "below" if scalar(v) else f"{len(v)} entries, below",
                        )
                    )
                    fence, body = (
                        ("```", v.rstrip("\n"))
                        if scalar(v)
                        else (
                            "```yaml",
                            yaml.safe_dump(v, sort_keys=False, width=100).strip(),
                        )
                    )
                    details.extend(
                        [
                            "",
                            f"<details><summary><code>{key}</code> default</summary>",
                            "",
                            fence,
                            body,
                            "```",
                            "",
                            "</details>",
                        ]
                    )
                else:
                    rows.append((f"`{key}`", self.note("config", *p), f"`{flow(v)}`"))

        walk(config, ())
        return [
            "## Settings",
            "",
            *self.intro("config"),
            f"Under `stack.{self.key}.config`. Maps merge across layers; lists are replaced whole.",
            "",
            *table(["Key", "Description", "Default"], rows),
            *details,
            "",
        ]

    def intro(self, section):
        text = self.note(section)
        return [cell(text), ""] if text else []

    def operators_section(self):
        rows = []
        for name, e in self.ops.items():
            sub = e.get("subscription") or {}
            versions = "<br>".join(f"`{v}`" for v in e.get("versions") or []) or "any"
            if e.get("upgradeApproval", "Automatic") != "Automatic":
                versions += f", {e['upgradeApproval']} approval"
            off = "" if self.own(e) else " (off)"
            rows.append(
                (
                    f"`install-{name}`{off}",
                    f"`{sub.get('name', '')}`",
                    f"`{sub.get('channel', '')}`",
                    f"`{sub.get('source', 'redhat-operators')}`",
                    f"`{e.get('namespace', '')}`",
                    versions,
                )
            )
        if not rows:
            return []
        return [
            "## Operators",
            "",
            (
                "Each renders into Policy `install` with `<name>-ns` and `<name>-status`. Pin with "
                "`operatorPolicies.<key>.versions` in a layer."
            ),
            "",
            *table(
                [
                    "Operator policy",
                    "Package",
                    "Channel",
                    "Source",
                    "Namespace",
                    "Versions",
                ],
                rows,
            ),
            "",
        ]

    def policies_section(self):
        md = [
            "## Policies",
            "",
            (
                "`<cluster>` is the ManagedCluster name, or hubName on the hub. "
                "`global.remediationAction: inform` overrides every action below."
            ),
            "",
        ]
        meta = [
            f"{label}: {', '.join(self.default[k])}."
            for k, label in (
                ("standards", "Standards"),
                ("controls", "Controls"),
                ("categories", "Categories"),
            )
            if self.default.get(k)
        ]
        if meta:
            md += [cell(" ".join(meta)), ""]
        for p, pv, items in self.policies:
            line = f"`{p}-{self.name}-<cluster>`"
            if pv.get("description"):
                line += f": {pv['description'].rstrip('.')}."
            if pv.get("dependencies"):
                line += (
                    " Depends on "
                    + ", ".join(
                        self.resolve(d, p, "Policy") for d in pv["dependencies"]
                    )
                    + "."
                )
            if pv.get("orderManifests"):
                line += (
                    " Applies "
                    + ", ".join(f"`{t}`" for t in pv["orderManifests"])
                    + " first, in order, then the rest."
                )
            if not self.own(pv):
                line += f" Off by default; turn on with `policies.{p}.enabled: true`."
            elif not self.on(pv, items):
                line += " Renders nothing by default: every template is off."
            rows = [
                (
                    f"`{p}-{n}`" + ("" if self.own(e) else " (off)"),
                    self.action(kind, e, pv),
                    self.severity(e, pv),
                    self.waits(e, p),
                    self.renders(kind, n, e, files),
                    e.get("description", ""),
                )
                for kind, n, e, files in items
            ]
            md += [f"### Policy `{p}`", "", cell(line), ""]
            if rows:
                md += [
                    *table(
                        [
                            "Template",
                            "Action",
                            "Severity",
                            "Waits for",
                            "Renders",
                            "Description",
                        ],
                        rows,
                    ),
                    "",
                ]
        return md

    def render(self):
        md = [HEADER, f"# {self.name}", ""]
        if self.chart.get("description"):
            md += [cell(self.chart["description"]), ""]
        if self.chart.get("home"):
            md += [f"Guide: {self.chart['home']}", ""]
        if self.stability:
            link = "https://policystk.io/reference/compatibility/#element-stability"
            md += [f"Stability: {self.stability} ([Compatibility]({link}))", ""]
        md += ["```yaml", "stack:", f"  {self.key}:", "    enabled: true", "```", ""]
        md += self.optional_section()
        if self.c.get("config"):
            md += self.settings_section(self.c["config"])
        md += self.operators_section() + self.policies_section()
        return "\n".join(md).rstrip("\n") + "\n"


def generate(element_path):
    """README content for one element, or None when it has no stack.<key> values."""
    values_file = element_path / "values.yaml"
    if not values_file.exists():
        return None
    chart_file = element_path / "Chart.yaml"
    chart = yaml.safe_load(chart_file.read_text()) if chart_file.exists() else {}
    text = values_file.read_text()
    element = Element(element_path, chart, yaml.safe_load(text) or {}, comments(text))
    return element.render() if element.c else None


def write_if_changed(path, content):
    if path.exists() and path.read_text() == content:
        return False
    path.write_text(content)
    return True


def elements(stack_dir):
    return sorted(
        p
        for p in Path(stack_dir).iterdir()
        if p.is_dir() and not p.name.startswith(".")
    )


def main(argv=None):
    parser = argparse.ArgumentParser(description="Generate stack/<element>/README.md")
    parser.add_argument(
        "--stack-dir",
        default="stack",
        help="directory containing elements (default: stack)",
    )
    parser.add_argument("--element", help="generate only this element")
    parser.add_argument(
        "--check", action="store_true", help="exit 1 when a README is missing or stale"
    )
    args = parser.parse_args(argv)

    if not Path(args.stack_dir).is_dir():
        # A framework copy has no stack/ until its first element is added.
        if args.stack_dir == parser.get_default("stack_dir") and not args.element:
            return 0
        print(f"error: {args.stack_dir} is not a directory")
        return 1
    paths = (
        [Path(args.stack_dir) / args.element]
        if args.element
        else elements(args.stack_dir)
    )
    stale = []
    for path in paths:
        content = generate(path) if path.is_dir() else None
        if content is None:
            if args.element:
                print(f"error: {path} has no stack.{camel(path.name)} values")
                return 1
            continue
        readme = path / "README.md"
        if args.check:
            if not readme.exists() or readme.read_text() != content:
                stale.append(readme)
        elif write_if_changed(readme, content):
            print(f"updated {readme}")
    if stale:
        print("Stale element READMEs, run python tools/doc-generator.py:")
        print("\n".join(f"  {p}" for p in stale))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
